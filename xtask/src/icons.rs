//! `cargo xtask gen-icons`: Material Symbols の SVG のコピーと定数の生成

use std::fmt::Write as _;
use std::fs;
use std::path::PathBuf;

use crate::{git_head, rustfmt, sync_outputs, workspace_root};

const MATERIAL_DESIGN_ICONS: &str =
    ".agents/skills/material-design-3-port/references/material-design-icons";
const ICONS_OUT_DIR: &str = "crates/md3-icons";

/// 埋め込むスタイルの上流のディレクトリ名
///
/// 並びは `md3_icons::IconStyle` のバリアントの並びと一致させる
const ICON_STYLES: &[&str] = &[
    "materialsymbolsoutlined",
    "materialsymbolsrounded",
    "materialsymbolssharp",
];

/// 埋め込む塗りの、上流のファイル名の接尾辞 (塗りなし、塗りあり の順)
///
/// ウェイト 400、グレード 0、サイズ 24px のファイルだけを対象にする
const ICON_FILLS: &[&str] = &["_24px.svg", "_fill1_24px.svg"];

pub(crate) fn generate(check: bool) -> Result<(), String> {
    let root = workspace_root();
    let upstream = root.join(MATERIAL_DESIGN_ICONS);
    let commit = git_head(&upstream)?;
    let web = upstream.join("symbols/web");

    let mut names: Vec<String> = fs::read_dir(&web)
        .map_err(|e| format!("failed to read {}: {e}", web.display()))?
        .filter_map(|entry| entry.ok())
        .filter(|entry| entry.path().is_dir())
        .filter_map(|entry| entry.file_name().to_str().map(str::to_owned))
        .collect();
    names.sort();
    if names.is_empty() {
        return Err(format!(
            "no icons in {} (is the submodule checked out?)",
            web.display()
        ));
    }

    // (crates/md3-icons からの相対パス, 内容)
    let mut outputs: Vec<(String, Vec<u8>)> = Vec::new();
    let mut consts = String::new();
    let mut all = String::new();
    for name in &names {
        // `arrow_back` を `ARROW_BACK` にする。数字で始まる名前は識別子にできないため `N` を前に付ける
        let mut ident = name.to_ascii_uppercase();
        if ident.starts_with(|c: char| c.is_ascii_digit()) {
            ident.insert(0, 'N');
        }
        let _ = writeln!(all, "{ident},");

        let _ = write!(
            consts,
            "/// `{name}`\npub const {ident}: Icon = Icon {{ name: \"{name}\", svgs: ["
        );
        for style in ICON_STYLES {
            consts.push('[');
            for suffix in ICON_FILLS {
                let file = format!("{name}{suffix}");
                let source = web.join(name).join(style).join(&file);
                let bytes = fs::read(&source)
                    .map_err(|e| format!("failed to read {}: {e}", source.display()))?;
                let relative = format!("assets/{style}/{file}");
                let _ = write!(consts, "include_str!(\"../{relative}\"),");
                outputs.push((relative, bytes));
            }
            consts.push_str("],");
        }
        consts.push_str("] };\n");
    }

    let generated = format!(
        "// Generated by `cargo xtask gen-icons`. DO NOT EDIT.
// Copied from Material Symbols (https://github.com/google/material-design-icons)
// Source: symbols/web/<name>/<style>/<name>{{{fills}}} @ {commit}
// Licensed under the Apache License, Version 2.0 (assets/LICENSE).

//! Material Symbols のアイコン

use crate::Icon;

{consts}
/// すべてのアイコン
pub const ALL: &[Icon] = &[
{all}];
",
        fills = ICON_FILLS.join(","),
    );
    outputs.push((
        "src/generated.rs".to_owned(),
        rustfmt(&root, &generated)?.into_bytes(),
    ));

    let license = upstream.join("LICENSE");
    outputs.push((
        "assets/LICENSE".to_owned(),
        fs::read(&license).map_err(|e| format!("failed to read {}: {e}", license.display()))?,
    ));
    let source_md = format!(
        "<!-- Generated by `cargo xtask gen-icons`. DO NOT EDIT. -->

# アイコンの出典

- 資料: Material Symbols (https://github.com/google/material-design-icons)
- コミット: `{commit}`
- パス: `symbols/web/<name>/<style>/<name>_24px.svg` (塗りなし) と `symbols/web/<name>/<style>/<name>_fill1_24px.svg` (塗りあり)
- スタイル: {styles}
- 軸: ウェイト 400、グレード 0、サイズ 24px
- ライセンス: Apache License 2.0 ([LICENSE](LICENSE) は取得元の `LICENSE` の写し)

SVG は無加工で `assets/<style>/` にコピーしている。取得条件を変えるときは `xtask` の `gen-icons` を変えて
`cargo xtask gen-icons` を実行する
",
        styles = ICON_STYLES
            .iter()
            .map(|style| format!("`{style}`"))
            .collect::<Vec<_>>()
            .join("、"),
    );
    outputs.push(("assets/SOURCE.md".to_owned(), source_md.into_bytes()));

    let out_dir = root.join(ICONS_OUT_DIR);
    let prune: Vec<PathBuf> = ICON_STYLES
        .iter()
        .map(|style| out_dir.join("assets").join(style))
        .collect();
    let stale = sync_outputs(&out_dir, &outputs, &prune, check)?;
    if !stale.is_empty() {
        return Err(format!(
            "icons are out of date; run `cargo xtask gen-icons`:\n  {}",
            stale.join("\n  ")
        ));
    }
    Ok(())
}
